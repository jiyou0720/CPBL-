#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>

#define TOTAL_NOTES 15

// 일기 구조체 정의 (요구사항: ID + 제목(날짜) + 본문)
typedef struct {
    int id;
    const char* date;
    const char* content;
} Note;

// 일기가 배치될 오브젝트(위치) 구조체
typedef struct {
    const char* location_name; // 위치 이름 (예: "주인공 방(비밀 방)")
    int has_note;              // 현재 일기가 숨겨져 있는지 여부 (0: 없음, 1: 있음)
    int note_index;            // 숨겨진 일기의 배열 인덱스
    int is_searched;           // 플레이어가 이미 조사를 완료했는지 여부
} SearchObject;

int main() {
    // 1. 원본 일기 데이터 배열 (15장)
    Note origin_notes[TOTAL_NOTES] = {
        {1, "0000.00.00", "오늘도 저택은 평화롭다.\n주인님께서는 평소처럼 아내분과 함께 정원을 거닐고 계신다..."},
        {2, "0000.00.00", "나는 다른 사용인들에게 집사님에 대한 이야기를 들었다.\n집사님은 가족이 없으시며..."},
        {3, "0000.00.00", "평소처럼 일에 몰두하고 있던 어느 날—\n산책하고 계셨던 부인이 쓰러지셨다..."},
        {4, "0000.00.00", "그분이 쓰러진 이후, 저택의 분위기는 서서히 변하기 시작했다.\n안색이 좋지 않으셨다..."},
        {5, "0000.00.00", "요 며칠 사이, 저택에서 이상한 일이 계속되고 있다.\n알고 지낸 사용인들이 보이지 않는다..."},
        {6, "0000.00.00", "오늘, 도서관 근처에 갔다가 이상한 광경을 목격했다.\n주인님이 누군가와 이야기를..."},
        {7, "0000.00.00", "사람들이 하나둘씩 사라지고 있다.\n처음에는 외출, 그 다음으로는 이직이라 생각했다..."},
        {8, "0000.00.00", "오늘… 확실히 보았다.\n외출 후 실종되었던 사용인이 복도 끝에 서 있었다. 사람이 아니었다..."},
        {9, "0000.00.00", "혼란스럽다.\n주인님.. 그리고 집사님은 무슨 생각이신 걸까—"},
        {10, "0000.00.00", "요즘 들어, 이상한 소리가 들리기 시작했다.\n“이곳은 위험해. 여기를 떠나야 해.”"},
        {11, "0000.00.00", "이런 일들이 일어나는 것을 보며 한 가지 깨달은 것이 있다.\n목소리는 사라진 사람들의 것이다..."},
        {12, "0000.00.00", "도망치려고 시도했다.\n몰래 문으로 나가려고 했지만 문이 잠겨있어서 나갈 수가 없었다..."},
        {13, "0000.00.00", "사라진 사람들의 목소리가 끊임없이 나에게 말한다.\n“그걸.. 파괴해야 해.. 그곳에 있어..”"},
        {14, "0000.00.00", "오늘, 집사님과 마주쳤다. 아무 말도 하지 않으셨지만 차가운 눈빛...\n귀신이 가장 위험한 게 아니다."},
        {15, "0000.00.00", "더 이상 시간을 지체할 수 없다. 나는 이 저택을 벗어날 것이다.\n“심장”을 찾아 이 모든 걸 끝내야 한다..."}
    };

    // 2. 기획하신 15개의 획득 위치 정의
    SearchObject objects[TOTAL_NOTES] = {
        {"주인공 방(비밀 방) - 첫 번째 흔적", 1, 0, 0},
        {"주인공 방(비밀 방) - 두 번째 흔적", 1, 0, 0},
        {"주인공 방(비밀 방) - 세 번째 흔적", 1, 0, 0},
        {"응접실(소파 사이)", 1, 0, 0},
        {"응접실(창문쪽 화분 아래)", 1, 0, 0},
        {"현관(신발장 쪽)", 1, 0, 0},
        {"연구실/서재(책장)", 1, 0, 0},
        {"연구실/서재(카펫 아래)", 1, 0, 0},
        {"드레스룸(옷들 사이)", 1, 0, 0},
        {"사용인 방(침대 옆 탁자 A)", 1, 0, 0},
        {"사용인 방(침대 옆 탁자 B)", 1, 0, 0},
        {"사용인 방(테라스)", 1, 0, 0},
        {"주 계단(큰 그림 뒤)", 1, 0, 0},
        {"1층 복도(조각상 내부)", 1, 0, 0},
        {"2층 복도(샹들리에 고리)", 1, 0, 0}
    };

    // 3. 랜덤 셔플을 위한 인덱스 배열 생성 및 섞기
    int shuffle_indices[TOTAL_NOTES];
    for (int i = 0; i < TOTAL_NOTES; i++) {
        shuffle_indices[i] = i;
    }

    srand(time(NULL)); // 랜덤 시드 초기화
    for (int i = TOTAL_NOTES - 1; i > 0; i--) {
        int j = rand() % (i + 1);
        int temp = shuffle_indices[i];
        shuffle_indices[i] = shuffle_indices[j];
        shuffle_indices[j] = temp;
    }

    // 섞인 인덱스를 위치 구조체에 매핑 (랜덤 배치 완료)
    for (int i = 0; i < TOTAL_NOTES; i++) {
        objects[i].note_index = shuffle_indices[i];
    }

    // 4. 테스트용 상호작용 루프 (게임 시뮬레이션)
    printf("==================================================\n");
    printf("  [시스템] 저택의 일기 데이터가 무작위로 숨겨졌습니다.\n");
    printf("==================================================\n\n");

    int menu;
    while (1) {
        printf("\n--- 현재 조사 가능한 위치 목록 ---\n");
        for (int i = 0; i < TOTAL_NOTES; i++) {
            printf("%2d. %s [%s]\n", i + 1, objects[i].location_name, 
                   objects[i].is_searched ? "조사완료" : "미조사");
        }
        printf(" 0. 게임 종료\n");
        printf("-----------------------------------\n");
        printf("조사할 오브젝트 번호를 선택하세요: ");
        
        if (scanf("%d", &menu) != 1) break;
        if (menu == 0) break;

        if (menu < 1 || menu > TOTAL_NOTES) {
            printf("올바른 번호가 아닙니다.\n");
            continue;
        }

        int target_idx = menu - 1;

        if (objects[target_idx].is_searched) {
            printf("\n[!] 이미 샅샅이 조사한 곳입니다. 더 이상 아무것도 없습니다.\n");
        } else {
            objects[target_idx].is_searched = 1; // 조사 처리
            int note_idx = objects[target_idx].note_index;
            
            printf("\n==================================================\n");
            printf("★ 오브젝트 검사 성공! [notes.dat]의 조각을 획득했습니다.\n");
            printf("--------------------------------------------------\n");
            printf("[ID: %04d] 날짜: %s\n", origin_notes[note_idx].id, origin_notes[note_idx].date);
            printf("위치: %s\n", objects[target_idx].location_name);
            printf("--------------------------------------------------\n");
            printf("%s\n", origin_notes[note_idx].content);
            printf("==================================================\n");
        }
    }

    printf("게임을 종료합니다.\n");
    return 0;
}

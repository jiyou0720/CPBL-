char map_get(GameState *gs, int x, int y) {
    if (x < 0 || x >= MAP_COLS || y < 0 || y >= MAP_ROWS) return T_WALL;
    return (gs->floor == 1) ? map1f[y][x] : map2f[y][x];
}

void map_set(GameState *gs, int x, int y, char tile) {
    if (x < 0 || x >= MAP_COLS || y < 0 || y >= MAP_ROWS) return;
    if (gs->floor == 1) map1f[y][x] = tile;
    else                map2f[y][x] = tile;
}

int map_walkable(GameState *gs, int x, int y) {
    char t = map_get(gs, x, y);
    return (t == T_FLOOR || t == T_DOOR  || t == T_STAIRS_D ||
            t == T_STAIRS_U || t == T_ITEM || t == T_NOTE   ||
            t == T_KEY  || t == T_PUZZLE  || t == T_TRAP    ||
            t == T_CORE || t == T_NPC);
}

int map_get_room(GameState *gs, int x, int y) {
    if (gs->floor == 1) {

        /* 손님방 (확장) */
        if (x >= 0 && x <= 24 && y >= 1 && y <= 8)
            return ROOM_GUESTROOM;

        /* 응접실 */
        if (x >= 0 && x <= 9 && y >= 10 && y <= 18)
            return ROOM_LOUNGE;

        /* 현관 */
        if (x >= 10 && x <= 20 && y >= 10 && y <= 18)
            return ROOM_ENTRANCE;

        /* 중앙 복도 */
        if (x >= 22 && x <= 40 && y >= 1 && y <= 18)
            return ROOM_CORRIDOR1;

        /* 유틸리티실 */
        if (x >= 42 && x <= 57 && y >= 1 && y <= 8)
            return ROOM_UTILITY;

        /* 연구실/서재 */
        if (x >= 42 && x <= 57 && y >= 10 && y <= 18)
            return ROOM_STUDY;

        /* 도서관 */
        if (x >= 59 && x <= 77 && y >= 1 && y <= 18)
            return ROOM_LIBRARY;
    }
    else {

        /* 침실 1 */
        if (x >= 0 && x <= 13 && y >= 1 && y <= 8)
            return ROOM_BED1;

        /* 창고 */
        if (x >= 0 && x <= 13 && y >= 10 && y <= 12)
            return ROOM_STORAGE;

        /* 드레스룸 */
        if (x >= 0 && x <= 13 && y >= 14 && y <= 18)
            return ROOM_DRESSING;

        /* 2층 복도 */
        if (x >= 15 && x <= 27 && y >= 1 && y <= 18)
            return ROOM_CORRIDOR2;

        /* 침실 2 */
        if (x >= 29 && x <= 43 && y >= 1 && y <= 8)
            return ROOM_BED2;

        /* 화장실 */
        if (x >= 29 && x <= 43 && y >= 10 && y <= 15)
            return ROOM_BATHROOM;

        /* 사용인실 (확장) */
        if (x >= 45 && x <= 61 && y >= 1 && y <= 18)
            return ROOM_SERVANT;

        /* 마스터 스위트 */
        if (x >= 63 && x <= 77 && y >= 1 && y <= 9)
            return ROOM_MASTER;

        /* 테라스 */
        if (x >= 63 && x <= 77 && y >= 10 && y <= 18)
            return ROOM_TERRACE;
    }

    return ROOM_NONE;
}

